import { Region } from '../types';

export interface HistoricalGeoJsonProperties {
  id: string;
  featureType: 'collar_point' | 'dispersion_polygon' | 'structural_trend_line';
  holeId?: string;
  name: string;
  region: Region;
  campaignYear: number;
  commodity: 'Au' | 'Cu' | 'Li' | 'REE';
  concentrationIndex: number; // 0 - 100 normalized geochemical concentration
  gradeLabel: string;
  depthInterceptM?: string;
  lithologyHost: string;
  auPpm: number;
  cuPct: number;
  liPpm: number;
  reePpm: number;
  pathfinderSummary: string;
}

export interface HistoricalGeoJsonFeature {
  type: 'Feature';
  properties: HistoricalGeoJsonProperties;
  geometry: {
    type: 'Point' | 'Polygon' | 'LineString';
    coordinates: any;
  };
}

